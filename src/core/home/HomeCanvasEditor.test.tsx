it('edits independent canvas styles, inherits them in new text and saves individual overrides', async () => {
  await mount()
  fireEvent.change(screen.getByLabelText('Color de fondo del lienzo'), { target: { value: '#123456' } })
  fireEvent.change(screen.getByLabelText('Color de acento del lienzo'), { target: { value: '#abcdef' } })
  fireEvent.change(screen.getByLabelText('Color de texto normal del lienzo'), { target: { value: '#ffffff' } })
  fireEvent.change(screen.getByLabelText('Tamaño general del texto'), { target: { value: '96' } })
  fireEvent.blur(screen.getByLabelText('Tamaño general del texto'))
  fireEvent.change(screen.getByRole('combobox', { name: 'Añadir componente' }), { target: { value: 'text' } })
  expect(screen.getByLabelText('Tamaño del texto')).toHaveValue(96)
  expect(screen.getByLabelText('Color')).toHaveValue('#ffffff')
  expect(screen.getByLabelText('Color de acento')).toHaveValue('#abcdef')
  expect(screen.getByLabelText('Alineación')).toHaveValue('center')
  fireEvent.change(screen.getByLabelText('Tamaño del texto'), { target: { value: '24' } })
  fireEvent.blur(screen.getByLabelText('Tamaño del texto'))
  fireEvent.click(screen.getByRole('button', { name: 'Restablecer Tamaño del texto' }))
  expect(screen.getByLabelText('Tamaño del texto')).toHaveValue(96)
  fireEvent.change(screen.getByLabelText('Color de acento'), { target: { value: '#ff0000' } })
  fireEvent.click(screen.getByRole('button', { name: 'Restablecer Color de acento' }))
  expect(screen.getByLabelText('Color de acento')).toHaveValue('#abcdef')
  fireEvent.change(screen.getByLabelText('Color'), { target: { value: '#fedcba' } })
  fireEvent.click(screen.getByRole('button', { name: 'Vertical' }))
  expect(screen.getByLabelText('Tamaño general del texto')).toHaveValue(48)
  fireEvent.change(screen.getByLabelText('Tamaño general del texto'), { target: { value: '32' } })
  fireEvent.blur(screen.getByLabelText('Tamaño general del texto'))
  fireEvent.click(screen.getByRole('button', { name: 'Guardar lienzo' }))
  await screen.findByText('Lienzo guardado y confirmado.')
  const config = vi.mocked(saveHomeCanvas).mock.calls[0][1]
  expect(config.landscape).toMatchObject({ backgroundColor: '#123456', accentColor: '#abcdef', color: '#ffffff', fontSize: 96 })
  expect(config.landscape.items[0]).toMatchObject({ type: 'text', color: '#fedcba' })
  expect(config.landscape.items[0].fontSize).toBeUndefined()
  expect(config.landscape.items[0].accentColor).toBeUndefined()
  expect(config.portrait.fontSize).toBe(32)
  expect(config.portrait.color).toBeUndefined()
})
