it('allows clearing and typing size digit by digit, commits on Enter or blur and saves the last focused value', async () => {
  const user = userEvent.setup()
  await mount()
  const size = screen.getByLabelText('Tamaño general del texto')
  await user.clear(size)
  expect(size).toHaveValue(null)
  await user.type(size, '3')
  expect(size).toHaveValue(3)
  expect(screen.queryByRole('status')).not.toBeInTheDocument()
  await user.type(size, '2{Enter}')
  expect(size).toHaveValue(32)
  await user.selectOptions(screen.getByRole('combobox', { name: 'Añadir componente' }), 'text')
  const textSize = screen.getByLabelText('Tamaño del texto')
  expect(textSize).toHaveValue(32)
  await user.clear(textSize)
  await user.type(textSize, '160')
  await user.click(screen.getByRole('button', { name: 'Guardar lienzo' }))
  await screen.findByText('Lienzo guardado y confirmado.')
  expect(vi.mocked(saveHomeCanvas).mock.calls[0][1].landscape).toMatchObject({
    fontSize: 32, items: [{ fontSize: 160 }],
  })
})
it('rejects empty, fractional and out-of-range sizes only on blur and allows correcting them', async () => {
  await mount()
  const size = screen.getByLabelText('Tamaño general del texto')
  for (const input of ['', '3', '24.5', '161']) {
    fireEvent.change(size, { target: { value: input } })
    expect(screen.queryByRole('status')).not.toBeInTheDocument()
    fireEvent.blur(size)
    expect(screen.getByRole('status')).toHaveTextContent('entre 16 y 160')
    expect(size).toHaveValue(48)
  }
  fireEvent.change(size, { target: { value: '16' } })
  fireEvent.blur(size)
  expect(screen.queryByRole('status')).not.toBeInTheDocument()
  expect(size).toHaveValue(16)
  fireEvent.click(screen.getByRole('button', { name: 'Restablecer Tamaño general del texto' }))
  expect(size).toHaveValue(48)
  fireEvent.click(screen.getByRole('button', { name: 'Vertical' }))
  expect(screen.getByLabelText('Tamaño general del texto')).toHaveValue(48)
})
