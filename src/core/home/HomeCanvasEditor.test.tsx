import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { getHomeCanvas, saveHomeCanvas, type HomeCanvasResponse } from '../../api/homeCanvas'
import HomeCanvasEditor from './HomeCanvasEditor'

vi.mock('../../api/homeCanvas', () => ({ getHomeCanvas: vi.fn(), saveHomeCanvas: vi.fn() }))
let saved: HomeCanvasResponse
beforeEach(() => {
  vi.clearAllMocks()
  vi.stubGlobal('ResizeObserver', class { observe() {} disconnect() {} })
  saved = {
    ok: true, gameId: 'EVENT', gameType: 'T1MER', readOnly: false, homeRevision: 'one',
    homeBackgroundUrls: { landscape: null, portrait: null },
    homeCanvas: { version: 1, landscape: { background: null, items: [] }, portrait: { background: null, items: [] } },
  }
  vi.mocked(getHomeCanvas).mockImplementation(async () => structuredClone(saved))
  vi.mocked(saveHomeCanvas).mockImplementation(async (_id, homeCanvas) => ({ ...saved, homeRevision: 'two', homeCanvas }))
})
afterEach(() => { cleanup(); vi.unstubAllGlobals() })
async function mount(advanced = true) {
  const dirty = vi.fn()
  render(<HomeCanvasEditor gameId="EVENT" gameName="Event" appearance={null} advanced={advanced} onDirtyChange={dirty} />)
  await screen.findByRole('button', { name: '+ QR' })
  return dirty
}
it('starts empty and keeps two independent drafts when changing orientation', async () => {
  const dirty = await mount()
  fireEvent.click(screen.getByRole('button', { name: '+ QR' }))
  expect(screen.getByRole('button', { name: 'Mover QR' })).toBeInTheDocument()
  expect(screen.getByRole('button', { name: '+ QR' })).toBeDisabled()
  fireEvent.click(screen.getByRole('button', { name: 'Vertical' }))
  expect(screen.queryByRole('button', { name: 'Mover QR' })).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: '+ Texto' }))
  fireEvent.change(screen.getByLabelText('Texto', { selector: 'textarea' }), { target: { value: 'Hola evento' } })
  fireEvent.click(screen.getByRole('button', { name: 'Horizontal' }))
  expect(screen.getByRole('button', { name: 'Mover QR' })).toBeInTheDocument()
  expect(screen.queryByText('Hola evento')).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Guardar lienzo' }))
  await screen.findByText('Lienzo guardado y confirmado.')
  const [id, config, revision] = vi.mocked(saveHomeCanvas).mock.calls[0]
  expect(id).toBe('EVENT')
  expect(revision).toBe('one')
  expect(config.landscape.items.map(item => item.type)).toEqual(['qr'])
  expect(config.portrait.items[0].text).toBe('Hola evento')
  expect(dirty).toHaveBeenLastCalledWith(false)
})
it('rejects overlaps and invalid sizes while allowing keyboard movement and removal', async () => {
  await mount()
  fireEvent.click(screen.getByRole('button', { name: '+ Texto' }))
  fireEvent.click(screen.getByRole('button', { name: '+ Jugadores' }))
  const panel = screen.getByRole('button', { name: 'Mover Jugadores' }).parentElement!
  expect(panel).toHaveStyle({ left: '360px' })
  expect(screen.queryByLabelText('Posición X')).not.toBeInTheDocument()
  expect(screen.queryByLabelText('Ancho')).not.toBeInTheDocument()
  fireEvent.keyDown(screen.getByRole('button', { name: 'Mover Jugadores' }), { key: 'ArrowLeft' })
  expect(panel).toHaveStyle({ left: '360px' })
  expect(screen.getByRole('status')).toHaveTextContent('No cabe')
  fireEvent.keyDown(screen.getByRole('button', { name: 'Mover Jugadores' }), { key: 'ArrowRight' })
  expect(panel).toHaveStyle({ left: '420px' })
  fireEvent.keyDown(screen.getByRole('button', { name: 'Redimensionar Jugadores' }), { key: 'ArrowRight' })
  expect(panel).toHaveStyle({ width: '420px' })
  fireEvent.click(screen.getByRole('button', { name: 'Eliminar componente' }))
  expect(screen.queryByRole('button', { name: 'Mover Jugadores' })).not.toBeInTheDocument()
})
it('shows color and resize controls only on the selected component', async () => {
  await mount()
  fireEvent.click(screen.getByRole('button', { name: '+ Texto' }))
  fireEvent.click(screen.getByRole('button', { name: '+ Jugadores' }))
  expect(screen.queryByRole('button', { name: 'Cambiar fondo Texto' })).not.toBeInTheDocument()
  expect(screen.queryByRole('button', { name: 'Redimensionar Texto' })).not.toBeInTheDocument()
  expect(screen.getByRole('button', { name: 'Cambiar fondo Jugadores' })).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Mover Texto' }))
  expect(screen.getByRole('button', { name: 'Cambiar fondo Texto' })).toBeInTheDocument()
  expect(screen.getByRole('button', { name: 'Redimensionar Texto' })).toBeInTheDocument()
  expect(screen.queryByRole('button', { name: 'Cambiar fondo Jugadores' })).not.toBeInTheDocument()
})
it('allows transparent and colored component backgrounds on Free and saves both orientations', async () => {
  await mount(false)
  fireEvent.click(screen.getByRole('button', { name: '+ Jugadores' }))
  expect(screen.queryByLabelText('Fondo del componente')).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Cambiar fondo Jugadores' }))
  expect(screen.getByLabelText('Fondo del componente')).toHaveFocus()
  fireEvent.change(screen.getByLabelText('Fondo del componente'), { target: { value: 'color' } })
  expect(screen.getByLabelText('Color de fondo del componente')).toBeEnabled()
  fireEvent.change(screen.getByLabelText('Color de fondo del componente'), { target: { value: '#123456' } })
  expect(document.querySelector('.home-widget-background')).toHaveStyle({ backgroundColor: '#123456' })
  fireEvent.click(screen.getByRole('button', { name: 'Vertical' }))
  fireEvent.click(screen.getByRole('button', { name: '+ Texto' }))
  fireEvent.click(screen.getByRole('button', { name: 'Cambiar fondo Texto' }))
  fireEvent.change(screen.getByLabelText('Fondo del componente'), { target: { value: 'transparent' } })
  expect(document.querySelector<HTMLElement>('.home-widget-background')?.style.backgroundColor).toBe('transparent')
  fireEvent.click(screen.getByRole('button', { name: 'Guardar lienzo' }))
  await screen.findByText('Lienzo guardado y confirmado.')
  const config = vi.mocked(saveHomeCanvas).mock.calls[0][1]
  expect(config.landscape.items[0].backgroundColor).toBe('#123456')
  expect(config.portrait.items[0].backgroundColor).toBe('transparent')
  fireEvent.change(screen.getByLabelText('Fondo del componente'), { target: { value: 'default' } })
  expect(document.querySelector('.home-widget-background')).toBeNull()
})
it('snaps pointer movement to the grid and resizes from the corner handle', async () => {
  vi.stubGlobal('PointerEvent', MouseEvent)
  const capture = vi.fn()
  await mount()
  fireEvent.click(screen.getByRole('button', { name: '+ Texto' }))
  const stage = document.querySelector('[data-home-stage]')!
  vi.spyOn(stage, 'getBoundingClientRect').mockReturnValue({ width: 960 } as DOMRect)
  const move = screen.getByRole('button', { name: 'Mover Texto' })
  Object.defineProperty(move, 'setPointerCapture', { value: capture })
  fireEvent.pointerDown(move, { button: 0, clientX: 100, clientY: 100 })
  fireEvent.pointerMove(move, { clientX: 161, clientY: 131 })
  fireEvent.pointerUp(move)
  expect(capture).toHaveBeenCalledOnce()
  expect(move.parentElement).toHaveStyle({ left: '120px', top: '60px' })
  const resize = screen.getByRole('button', { name: 'Redimensionar Texto' })
  Object.defineProperty(resize, 'setPointerCapture', { value: capture })
  fireEvent.pointerDown(resize, { button: 0, clientX: 100, clientY: 100 })
  fireEvent.pointerMove(resize, { clientX: 130, clientY: 130 })
  fireEvent.pointerUp(resize)
  expect(move.parentElement).toHaveStyle({ width: '420px', height: '180px' })
})
it('preserves a failed save and requires explicit reload without silently discarding', async () => {
  await mount()
  vi.mocked(saveHomeCanvas).mockRejectedValue(new Error('HomeChanged'))
  fireEvent.click(screen.getByRole('button', { name: '+ QR' }))
  fireEvent.click(screen.getByRole('button', { name: 'Guardar lienzo' }))
  expect(await screen.findByRole('alert')).toHaveTextContent('HomeChanged')
  expect(screen.getByRole('button', { name: 'Guardar lienzo' })).toBeDisabled()
  fireEvent.click(screen.getByRole('button', { name: 'Recargar lienzo' }))
  expect(screen.getByRole('alertdialog')).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Seguir editando' }))
  expect(screen.getByRole('button', { name: 'Mover QR' })).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Recargar lienzo' }))
  fireEvent.click(screen.getByRole('button', { name: 'Recargar y descartar' }))
  await waitFor(() => expect(screen.queryByRole('button', { name: 'Mover QR' })).not.toBeInTheDocument())
})
it('allows Free layout/text editing but gates backgrounds and custom text colors', async () => {
  await mount(false)
  fireEvent.click(screen.getByRole('button', { name: '+ Texto' }))
  expect(screen.getByLabelText('Texto', { selector: 'textarea' })).not.toBeDisabled()
  expect(screen.getByLabelText('Color (Event)')).toBeDisabled()
  fireEvent.click(screen.getByText('Fondo de este lienzo (Event)'))
  expect(screen.getByLabelText('Subir imagen o vídeo')).toBeDisabled()
})
